/**
 * Сводка по конкурсу для админ-панели: качество аудитории и доставка
 * уведомлений победителям.
 */
export class ContestStatsDto {
  contestId: number;

  /** Уникальные участники, всего. */
  participantsTotal: number;

  /** Прошли перепроверку подписки (или она не проводилась). */
  participantsValid: number;

  /** Отписались после участия — в розыгрыш не шли. */
  participantsUnsubscribed: number;

  /**
   * Проводилась ли перепроверка. Пока null, participantsUnsubscribed = 0
   * означает «не проверяли», а не «никто не отписался» — без этого поля
   * ноль читался бы неверно.
   */
  subscriptionsCheckedAt: Date | null;

  /**
   * Строк победителей всего — включая отказавшихся и просроченных. При
   * автодоборе на одном месте побывает несколько человек, поэтому это число
   * может превышать количество призовых мест.
   */
  winnersTotal: number;

  /** Приз принят (или подтверждение у конкурса не требуется). */
  winnersConfirmed: number;

  /** Ждут решения победителя — срок ещё идёт. */
  winnersPending: number;

  /** Отказались сами. */
  winnersDeclined: number;

  /** Не отозвались до дедлайна. */
  winnersExpired: number;

  /**
   * Призовые места, которые сейчас закрыты живым победителем (CONFIRMED или
   * ожидающим решения). Меньше prizePlaces — значит место осталось без
   * победителя: очередь жеребьёвки исчерпалась, нужно решение оператора.
   */
  placesFilled: number;

  /** Сколько призовых мест у конкурса — чтобы placesFilled было с чем сравнить. */
  prizePlaces: number;

  /** Победители, получившие личное уведомление. */
  notificationsDelivered: number;

  /**
   * Уведомление не доставлено — чаще всего победитель не запускал бота
   * (бот не может писать первым). Таким имеет смысл написать вручную.
   */
  notificationsFailed: number;
}
