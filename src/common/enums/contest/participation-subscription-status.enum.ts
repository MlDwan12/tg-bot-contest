/**
 * Состояние участника по обязательным каналам на момент подведения итогов.
 *
 * VALID — подписка подтверждена (или перепроверка не проводилась: подписку
 * проверяли при участии, и поводов считать иначе нет).
 * UNSUBSCRIBED — на финише подписки уже не было, в розыгрыш не идёт.
 */
export enum ParticipationSubscriptionStatus {
  VALID = 'valid',
  UNSUBSCRIBED = 'unsubscribed',
}
