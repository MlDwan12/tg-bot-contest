/**
 * Состояние выдачи приза победителю.
 *
 * PENDING_CONFIRMATION — победитель определён, ждём его подтверждения до
 * дедлайна. Ставится, только когда у конкурса включено requireWinnerConfirmation.
 * CONFIRMED — приз принят. Либо подтверждение не требовалось: тогда статус
 * проставляется сразу при розыгрыше, и конкурс идёт как до появления Ш10.
 * DECLINED — победитель отказался сам.
 * EXPIRED — не отозвался до дедлайна.
 *
 * Освободившееся место (DECLINED/EXPIRED) занимает следующий по жеребьёвке —
 * порядком замен служит то же перемешивание shuffle(seed, pool), что определило
 * победителей. Если очередь кончилась, место остаётся незакрытым и об этом
 * узнаёт администратор.
 */
export enum ContestWinnerStatus {
  PENDING_CONFIRMATION = 'pending_confirmation',
  CONFIRMED = 'confirmed',
  DECLINED = 'declined',
  EXPIRED = 'expired',
}
